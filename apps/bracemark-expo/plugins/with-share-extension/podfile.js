const { withPodfile } = require('expo/config-plugins');

const { shareExtensionNames } = require('./util');

// THE SHARE EXTENSION'S OWN BLOCK IN THE GENERATED PODFILE.
//
// The extension target gets its own autolinking pass, so the native modules
// its React Native instance needs are linked into its binary:
// `use_expo_modules!(exclude: …)` for the Expo modules, then the community
// ones, then `use_react_native!`.
//
// **The autolinking command and the `use_react_native!` call are COPIED FROM
// THE APP'S BLOCK** rather than restated, so the extension follows whatever the
// SDK's Podfile template says on the next bump. (Under expo-share-extension
// the two blocks had already drifted: the app's command was `node --eval
// require('expo/bin/autolinking')`, the extension's `npx
// expo-modules-autolinking`.) A template that no longer has either throws here
// — re-read the new template and update the patterns below.
//
// **The community modules are filtered, which `use_native_modules!` cannot do.**
// It is exactly `link_native_modules!(list_native_modules!(config_command))`
// (react-native/scripts/cocoapods/autolinking.rb), so the block calls the two
// halves and drops `excludedCommunityModules` between them. NOT by filtering
// the config command's JSON: `list_native_modules!` also writes that JSON to
// `build/generated/autolinking/autolinking.json`, the file codegen reads to
// build the providers BOTH targets share, and an extension-shaped copy there
// would unregister Screens' and Gesture Handler's components from the APP.
// Filtering the list after it has been written leaves that file the app's.
//
// Why filter at all: one of them is worse than dead weight. The sheet's Save
// path loads react-native-quick-crypto, whose react-native-nitro-modules runs
// `installWorkletsSupport()` on import — a try/catch'd `require` of
// react-native-worklets. With Worklets linked, that require installs its
// TurboModule, and `WorkletsModuleProxy`'s constructor builds a whole second
// Hermes runtime in a process with a 120MB cap (docs/share-sheet.md, _the share
// extension has almost no memory to spare_, rule 3).
//
// ⚠ WHICH IS ALSO WHY THAT LIST IS SHORT. Codegen's
// `RCTThirdPartyComponentsProvider`, which both targets link, is an
// NSDictionary LITERAL of `NSClassFromString(@"…ComponentView")`, and in a
// target that does not link the library that class is nil — an uncaught
// NSInvalidArgumentException the moment React Native starts, after a clean
// prebuild, compile and link. So a library the APP registers a Fabric
// component from cannot be excluded, whatever the sheet uses; check
// `ios/build/generated/ios/RCTThirdPartyComponentsProvider.mm` after a
// prebuild before adding one. TurboModules are safe: that provider maps names
// to strings and resolves them lazily.
//
// `expo-updates` is always excluded, as upstream always did: its
// AppController asserts when the extension starts.

const MARKER = '# Generated by plugins/with-share-extension/podfile.js';

// `if ENV['EXPO_USE_COMMUNITY_AUTOLINKING'] == '1'` … `end`, as the template
// indents it inside the app's target block.
const CONFIG_COMMAND = /^ {2}if ENV\['EXPO_USE_COMMUNITY_AUTOLINKING'\][\s\S]*?^ {2}end$/m;
const USE_FRAMEWORKS = /^ {2}use_frameworks! .*$/gm;
const USE_REACT_NATIVE = /^ {2}use_react_native!\([\s\S]*?^ {2}\)$/m;
// The call inside the app's post_install, which the build-settings loop
// follows.
const POST_INSTALL_CALL = /^( *)react_native_post_install\([\s\S]*?^\1\)$/m;

const POST_INSTALL_MARKER = '# with-share-extension: pods may use app-only API';
// Pods are built once for both targets, and Xcode refuses UIApplication-only
// API in an extension's dependencies unless each pod says it may use it. The
// share extension never reaches those paths (docs/share-sheet.md, _what an
// app-extension process breaks_), but the pods must still link.
const POST_INSTALL = `    ${POST_INSTALL_MARKER}
    installer.pods_project.targets.each do |target|
      unless target.name == 'Sentry'
        target.build_configurations.each do |config|
          config.build_settings['APPLICATION_EXTENSION_API_ONLY'] = 'No'
        end
      end
    end`;

function fail(what) {
  throw new Error(
    `with-share-extension: could not find ${what} in the app's target block of ` +
      `ios/Podfile. The Expo Podfile template has changed — read the new one, then ` +
      `update the pattern in plugins/with-share-extension/podfile.js. Left unpatched, ` +
      `the share extension would not link React Native at all.`,
  );
}

function shareExtensionBlock(appBlock, { targetName, excludedExpoModules, excludedCommunity }) {
  const configCommand = CONFIG_COMMAND.exec(appBlock)?.[0] ?? fail('the autolinking command');
  const useFrameworks = appBlock.match(USE_FRAMEWORKS) ?? fail('use_frameworks!');
  const useReactNative = USE_REACT_NATIVE.exec(appBlock)?.[0] ?? fail('use_react_native!');
  const exclude = [...new Set(['expo-updates', ...excludedExpoModules])];

  return `
${MARKER}: the iOS share extension's
# own autolinking pass. Expo modules minus app.config.ts's excludedExpoModules,
# community modules minus its excludedCommunityModules — the latter filtered
# AFTER list_native_modules! has written autolinking.json, which codegen reads
# for both targets.
target '${targetName}' do
  exclude = ${JSON.stringify(exclude)}
  use_expo_modules!(exclude: exclude)

${configCommand}

  share_native_modules = list_native_modules!(config_command)
  share_native_modules[:ios_packages].reject! do |package|
    ${JSON.stringify(excludedCommunity)}.include?(package[:name])
  end
  config = link_native_modules!(share_native_modules)

${useFrameworks.join('\n')}

${useReactNative}
end
`;
}

const withShareExtensionPodfile = (config, props) =>
  withPodfile(config, (cfg) => {
    const { targetName } = shareExtensionNames(cfg);
    let source = cfg.modResults.contents;

    // Re-run on a prebuild without --clean: the block is already there.
    if (source.includes(MARKER)) return cfg;

    const appStart = source.search(/^target '/m);
    if (appStart === -1) fail("the app's `target` line");
    const appBlock = source.slice(appStart);

    const call = POST_INSTALL_CALL.exec(source) ?? fail('react_native_post_install');
    const afterCall = call.index + call[0].length;
    source = `${source.slice(0, afterCall)}\n${POST_INSTALL}${source.slice(afterCall)}`;

    source = `${source.trimEnd()}\n${shareExtensionBlock(appBlock, {
      targetName,
      excludedExpoModules: props.excludedExpoModules,
      excludedCommunity: props.excludedCommunityModules,
    })}`;

    cfg.modResults.contents = source;
    return cfg;
  });

module.exports = { withShareExtensionPodfile, MARKER };
