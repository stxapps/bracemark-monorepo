const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

// Android 12+ can transfer app data between devices even with allowBackup=false.
// Exclude every backup domain in BOTH modes, including device-protected storage.
// This covers decrypted SQLite/files as well as SecureStore and native prefs.
const BACKUP_DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];
const EXCLUSIONS = BACKUP_DOMAINS.map(
  (domain) => `    <exclude domain="${domain}" path="." />`,
).join('\n');
const EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-manifest-policy.js. -->
<data-extraction-rules>
  <cloud-backup>
${EXCLUSIONS}
  </cloud-backup>
  <device-transfer>
${EXCLUSIONS}
  </device-transfer>
</data-extraction-rules>
`;

/**
 * Android policy that has no corresponding Expo app-config field.
 *
 * Keep layout LTR until the direction-sensitive UI/gestures are qualified for
 * RTL. Backup is disabled in app.config.ts; these rules also exclude device
 * transfer on manufacturers that do not apply allowBackup to that mode.
 * android/ is generated, so both the manifest and XML belong to prebuild.
 * → docs/expo-build.md, _android manifest policy_.
 */
const withAndroidManifestPolicy = (config) => {
  config = withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:supportsRtl'] = 'false';
    application.$['android:fullBackupContent'] = 'false';
    application.$['android:dataExtractionRules'] = '@xml/bracemark_data_extraction_rules';
    return cfg;
  });

  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'bracemark_data_extraction_rules.xml'), EXTRACTION_RULES);
      return cfg;
    },
  ]);
};

module.exports = withAndroidManifestPolicy;
