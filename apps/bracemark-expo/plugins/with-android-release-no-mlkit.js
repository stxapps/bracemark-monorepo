const fs = require('fs');
const path = require('path');
const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');

/**
 * Keeps expo-dev-launcher's ML Kit barcode scanner out of RELEASE Android builds.
 *
 * The dev launcher's "scan a QR code to open a dev server" button is debug-only
 * code (`src/debug/…/HomeViewModel.kt`), but its build.gradle declares
 * `play-services-code-scanner` and `mlkit:barcode-scanning` as plain
 * `implementation`, and on Android the whole module is autolinked into every
 * variant (iOS marks it `debugOnly` in expo-module.config.json; Android has no
 * such flag). R8 strips the unreferenced Java, but not what else those AARs
 * bring, so a release build shipped:
 *
 * - `libbarhopper_v3.so` — ~5 MB per ABI, the single largest native library we
 *   don't use;
 * - `MlKitInitProvider`, a ContentProvider that runs at EVERY app start, plus
 *   ML Kit's component-discovery service;
 * - `com.google.mlkit.vision.DEPENDENCIES = barcode_ui` meta-data (from the dev
 *   launcher's own main manifest), which asks Play Services to download the
 *   barcode UI module to every device that installs the app.
 *
 * Removing the dev launcher itself from release isn't on offer: the generated
 * ExpoModulesPackageList is shared by all variants and names its classes, and
 * its release source set is a deliberate no-op stub. So this removes only what
 * the stub doesn't need — the ML Kit artifacts, from the `release*`
 * configurations — and the meta-data, via a release-only manifest overlay.
 * Debug keeps all of it, so the QR scanner still works in a dev build.
 * → docs/expo-build.md, _android release — the dev launcher's ML Kit_.
 *
 * Nothing in the release code path references these classes; if that changes
 * upstream, R8 fails the release build with "Missing class com.google.mlkit…",
 * which is the signal to revisit this rather than add a -dontwarn.
 */
const MARKER = '// bracemark: no ML Kit in release';

const BLOCK = `
${MARKER} — see plugins/with-android-release-no-mlkit.js
configurations.matching { it.name.startsWith('release') }.configureEach {
    exclude group: 'com.google.mlkit'
    exclude group: 'com.google.android.odml'
    exclude group: 'com.google.android.gms', module: 'play-services-code-scanner'
    exclude group: 'com.google.android.gms', module: 'play-services-mlkit-barcode-scanning'
}
`;

// `src/release/` overlays `src/main/` for the release variant only, and the
// template doesn't create it, so this file is ours alone.
const RELEASE_MANIFEST = `<!-- Generated by plugins/with-android-release-no-mlkit.js. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <application>
        <meta-data
            android:name="com.google.mlkit.vision.DEPENDENCIES"
            tools:node="remove" />
    </application>
</manifest>
`;

const withAndroidReleaseNoMlkit = (config) => {
  config = withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('with-android-release-no-mlkit: expected a groovy app/build.gradle');
    }
    if (!cfg.modResults.contents.includes(MARKER)) {
      cfg.modResults.contents += BLOCK;
    }
    return cfg;
  });

  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), RELEASE_MANIFEST);
      return cfg;
    },
  ]);
};

module.exports = withAndroidReleaseNoMlkit;
