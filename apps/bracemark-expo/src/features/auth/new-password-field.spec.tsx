import * as React from 'react';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react-native';

import { NEW_PASSWORD_COPY } from '@stxapps/react';

import { NewPasswordField, useNewPassword } from './new-password-field';

// The native half of web-ui's new-password-field.spec.tsx. `useNewPassword` is THE
// GATE on a new password here too, at create-account and at Settings → change
// password alike, and it is a separate copy of the logic, not an import of web's: the
// two once drifted (Settings scored with no penalty terms), and nothing but a spec on
// each side would notice them drifting again. Native differs in two places that
// matter here, and both are pinned: the words are generated by a lazy initializer, so
// the field is never empty, not even on the first render; and there is no `failed`
// rung, the packs being on disk.
//
// The real estimator runs (the packs are `require`d, so there is no network), hence
// the timeouts on the cases that type.

const LABEL = 'New password';
const SHOWN = 'Your new password';

function probe(username: string | undefined = 'wit_e2e', currentPassword?: string) {
  const result = { current: null as ReturnType<typeof useNewPassword> | null };
  const renders: string[] = [];
  function Probe() {
    const control = useNewPassword({ username, currentPassword });
    result.current = control;
    renders.push(control.password);
    return <NewPasswordField control={control} label={LABEL} shownLabel={SHOWN} />;
  }
  render(<Probe />);
  return {
    renders,
    get current() {
      if (!result.current) throw new Error('the probe never rendered');
      return result.current;
    },
  };
}

const field = () => screen.getByLabelText(LABEL);
const type = (value: string) => fireEvent.changeText(field(), value);
const settle = (view: ReturnType<typeof probe>) =>
  waitFor(() => expect(view.current.message.tone).not.toBe('muted'), { timeout: 30_000 });

describe('useNewPassword (native) — the generated default', () => {
  it('holds generated words from the very first render, with the gate open', () => {
    const view = probe();

    // Web generates in an effect (hydration), so its first frame is empty. Native has
    // no SSR, and an empty first frame would flash the "empty" rung under the field.
    expect(view.renders[0]).toMatch(/^[a-z]+(-[a-z]+){6}$/);
    expect(field().props.value).toBe(view.current.password);
    expect(view.current.generated).toBe(true);
    expect(view.current.ok).toBe(true);
    expect(screen.getByText(NEW_PASSWORD_COPY.generated)).toBeTruthy();
    expect(screen.getByText(NEW_PASSWORD_COPY.generatedHelp)).toBeTruthy();
  });

  // The field iOS and Android read. Masked, and a NEW password, so neither offers
  // the saved login to fill it.
  it('is a masked new-password field', () => {
    probe();

    expect(field().props.secureTextEntry).toBe(true);
    expect(field().props.autoComplete).toBe('new-password');
  });

  it('replaces the words on Regenerate, and the gate stays open', () => {
    const view = probe();
    const first = view.current.password;

    fireEvent.press(screen.getByRole('button', { name: NEW_PASSWORD_COPY.regenerate }));

    expect(view.current.password).not.toBe(first);
    expect(view.current.generated).toBe(true);
    expect(view.current.ok).toBe(true);
  });
});

describe('useNewPassword (native) — editing is choosing your own', () => {
  it('shuts the gate the moment the words are edited, and says so under the field', async () => {
    const view = probe();

    type('short');

    expect(view.current.generated).toBe(false);
    expect(view.current.ok).toBe(false);
    expect(screen.getByText(NEW_PASSWORD_COPY.ownHelp)).toBeTruthy();
    await settle(view);
    expect(view.current.ok).toBe(false);
  }, 30_000);

  it('holds an edit to the entropy floor, however long it is', async () => {
    const view = probe();

    type('password password password');
    await settle(view);

    expect(view.current.message.tone).toBe('error');
    expect(view.current.ok).toBe(false);
  }, 30_000);

  // The penalty term, which Settings once omitted on this platform as on web.
  it('penalises a password built out of the username', async () => {
    const view = probe('correcthorsebatterystaple');

    type('correcthorsebatterystaple');
    await settle(view);

    expect(view.current.message.tone).toBe('error');
  }, 30_000);

  it('scores the canonical password, so trailing spaces buy no entropy', async () => {
    const view = probe();

    type('ilovemydogsomuchyess  ');
    await settle(view);

    expect(view.current.ok).toBe(false);
  }, 30_000);

  it('opens for one that clears both floors, submits it verbatim, and Regenerate gets back', async () => {
    const view = probe();

    type('  Qx7-vT2m_pR9wLd4Zk1B-nH6  ');
    await settle(view);
    expect(view.current.ok).toBe(true);
    expect(view.current.password).toBe('  Qx7-vT2m_pR9wLd4Zk1B-nH6  ');

    fireEvent.press(screen.getByRole('button', { name: NEW_PASSWORD_COPY.regenerate }));
    expect(view.current.generated).toBe(true);
    expect(view.current.ok).toBe(true);
  }, 30_000);
});

describe('useNewPassword (native) — the current password', () => {
  it('stays shut for the current password, compared canonical', async () => {
    const view = probe(undefined, 'Qx7-vT2m_pR9wLd4Zk1B-nH6');

    type(' Qx7-vT2m_pR9wLd4Zk1B-nH6 ');
    await settle(view);

    expect(view.current.message.text).toBe('That’s your current password.');
    expect(view.current.ok).toBe(false);
  }, 30_000);

  it('passes the generated words, which are not the current password', () => {
    const view = probe(undefined, 'Qx7-vT2m_pR9wLd4Zk1B-nH6');

    expect(view.current.ok).toBe(true);
  });
});

describe('NewPasswordField (native) — showing the words', () => {
  // ⚠ The reveal must not swap the native view (password-input.tsx): iOS read a
  // filled secure field going away as a submission and raised Save Password? before
  // any account existed. Same element, `secureTextEntry` flipped, the whole value in
  // a box beside it.
  it('reveals in place and shows the whole password in a box, then hides it', () => {
    const view = probe();
    const before = field();

    fireEvent.press(screen.getByRole('button', { name: 'Show password' }));

    expect(field()).toBe(before);
    expect(field().props.secureTextEntry).toBe(false);
    expect(field().props.multiline).toBeFalsy();
    expect(screen.getByLabelText(SHOWN)).toBeTruthy();
    expect(screen.getByText(view.current.password)).toBeTruthy();

    fireEvent.press(screen.getByRole('button', { name: 'Hide password' }));
    expect(screen.queryByLabelText(SHOWN)).toBeNull();
  });

  it('keeps the box on the password as it changes', () => {
    probe();
    fireEvent.press(screen.getByRole('button', { name: 'Show password' }));

    type('my-own-edited-password');

    expect(screen.getByText('my-own-edited-password')).toBeTruthy();
  });
});

describe('NewPasswordField (native) — Copy beside Regenerate', () => {
  it('copies the password in the field, not the words an edit replaced', async () => {
    const Clipboard = jest.requireMock<{ setStringAsync: jest.Mock }>('expo-clipboard');
    Clipboard.setStringAsync.mockClear();
    probe();

    type('my-own-edited-password');
    await act(async () => {
      fireEvent.press(screen.getByRole('button', { name: 'Copy' }));
    });

    expect(Clipboard.setStringAsync).toHaveBeenCalledWith('my-own-edited-password');
    expect(screen.getByText('Copied')).toBeTruthy();
  });

  // Regenerate is the way back to generated words, and a "Copied" that outlived it
  // would claim the NEW words were copied.
  it('takes "Copied" back when Regenerate replaces the password', async () => {
    probe();

    await act(async () => {
      fireEvent.press(screen.getByRole('button', { name: 'Copy' }));
    });
    expect(screen.getByText('Copied')).toBeTruthy();

    fireEvent.press(screen.getByRole('button', { name: NEW_PASSWORD_COPY.regenerate }));
    expect(screen.queryByText('Copied')).toBeNull();
  });
});

jest.mock('expo-clipboard', () => ({
  setStringAsync: jest.fn(() => Promise.resolve(true)),
}));
