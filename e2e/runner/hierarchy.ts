import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { type CaseStepContext } from './native-run';

// Reading the device's screen the way Maestro reports it, for the host-side
// steps that need geometry a flow cannot express (native-run.ts, `CaseStep`).
//
// The units are the driver's own: iOS reports points and Android pixels, and a
// Maestro `swipe` takes coordinates in the same units on each, so a box read here
// can be handed straight back to a generated flow with no scale conversion.

export interface HierarchyNode {
  attributes?: Record<string, string>;
  children?: HierarchyNode[];
}

export interface Box {
  left: number;
  top: number;
  right: number;
  bottom: number;
}

export interface Point {
  x: number;
  y: number;
}

export function parseHierarchy(output: string): HierarchyNode {
  const start = output.indexOf('{');
  if (start === -1) throw new Error('maestro hierarchy printed no JSON');
  return JSON.parse(output.slice(start)) as HierarchyNode;
}

export function findNodes(
  root: HierarchyNode,
  predicate: (attributes: Record<string, string>) => boolean,
): HierarchyNode[] {
  const found: HierarchyNode[] = [];
  const walk = (node: HierarchyNode) => {
    if (node.attributes && predicate(node.attributes)) found.push(node);
    for (const child of node.children ?? []) walk(child);
  };
  walk(root);
  return found;
}

export function boxOf(node: HierarchyNode): Box {
  const match = /\[(-?\d+),(-?\d+)\]\[(-?\d+),(-?\d+)\]/.exec(node.attributes?.bounds ?? '');
  if (!match) throw new Error(`node has no bounds: ${JSON.stringify(node.attributes)}`);
  const [left, top, right, bottom] = match.slice(1).map(Number);
  return { left, top, right, bottom };
}

export function centerOf(box: Box): Point {
  return { x: Math.round((box.left + box.right) / 2), y: Math.round((box.top + box.bottom) / 2) };
}

// The single node whose accessible name and text both match — a settings row's
// rename field is named "List name" and carries the list's name as its value.
export function onlyNode(
  root: HierarchyNode,
  name: string,
  text: string | undefined,
  what: string,
): HierarchyNode {
  const nodes = findNodes(
    root,
    (attributes) =>
      attributes.accessibilityText === name && (text === undefined || attributes.text === text),
  );
  if (nodes.length !== 1) throw new Error(`expected one ${what}, found ${nodes.length}`);
  return nodes[0];
}

// The control named `name` on the same row as `anchor`: the one whose vertical
// centre falls inside the anchor's box.
export function sameRow(root: HierarchyNode, anchor: Box, name: string, what: string): Box {
  const boxes = findNodes(root, (attributes) => attributes.accessibilityText === name)
    .map(boxOf)
    .filter((box) => {
      const y = (box.top + box.bottom) / 2;
      return y >= anchor.top && y <= anchor.bottom;
    });
  if (boxes.length !== 1) throw new Error(`expected one ${what} on the row, found ${boxes.length}`);
  return boxes[0];
}

// A one-command flow performing a real touch drag between two points, written
// under the case's artifacts so the exact gesture that ran is on record.
//
// Slow on purpose. A native settings row lifts on a LONG PRESS of its grip
// (gesture-handler `activateAfterLongPress`, 200ms — settings/drag-sort.tsx), and
// Maestro's swipe presses and starts moving at once, so the finger has to stay
// inside the platform's touch slop for that long before it travels. Measured on
// the Pixel 8 AVD: a 3s and a 6s swipe over ~250px never lifted the row, 15s
// did; the iPhone 17 Pro simulator lifted at 3s and still does at 15s.
export async function writeDragFlow(
  context: CaseStepContext,
  label: string,
  from: Point,
  to: Point,
): Promise<string> {
  const dir = join(context.caseDir, 'generated');
  await mkdir(dir, { recursive: true });
  const path = join(dir, `${context.index}-${label}.yaml`);
  await writeFile(
    path,
    [
      '# Generated by runner/hierarchy.ts from the hierarchy read just before it.',
      'appId: com.bracemark.app',
      '---',
      '- swipe:',
      `    start: ${from.x}, ${from.y}`,
      `    end: ${to.x}, ${to.y}`,
      '    duration: 15000',
      '- waitForAnimationToEnd',
      '',
    ].join('\n'),
    'utf8',
  );
  return path;
}

// The one node carrying a `testID` — Maestro reports it as `resource-id` on both
// platforms.
export function boxById(root: HierarchyNode, id: string): Box {
  const nodes = findNodes(root, (attributes) => attributes['resource-id'] === id);
  if (nodes.length !== 1) throw new Error(`expected one #${id}, found ${nodes.length}`);
  return boxOf(nodes[0]);
}

// A link row's box, found by the url it shows. A row's accessible name is a
// composite that carries the url (docs/e2e.md, _a composite row name is not an
// inventory_), and the row's inner nodes can carry it too, so the widest match
// is the row itself. Null when no mounted node carries it.
export function rowBoxByText(root: HierarchyNode, text: string): Box | null {
  const boxes = findNodes(root, (attributes) =>
    [attributes.accessibilityText, attributes.text].some((value) => value?.includes(text)),
  ).map(boxOf);
  if (boxes.length === 0) return null;
  const area = (box: Box) => (box.right - box.left) * (box.bottom - box.top);
  return boxes.reduce((widest, box) => (area(box) > area(widest) ? box : widest));
}

// Whether `inner` is painted wholly inside `outer`. Viewport claims need this
// rather than a visibility assertion: FlashList keeps rows mounted past both
// edges, and a mounted row is in the tree whether or not it is on screen.
export function isInside(inner: Box, outer: Box): boolean {
  return (
    inner.top >= outer.top &&
    inner.bottom <= outer.bottom &&
    inner.left >= outer.left &&
    inner.right <= outer.right
  );
}

export function formatBox(box: Box): string {
  return `[${box.left},${box.top}][${box.right},${box.bottom}]`;
}
