// Emits the two scripts that take a read-mode copy inside a live page on iOS/Android,
// both from ONE bundle of the converter the browser extension uses
// (@stxapps/web-react/lib/reader-doc-from-page — Readability, then sanitized blocks):
//
//   apps/bracemark-expo/share-extension/preprocessing.js
//       The iOS share extension's NSExtensionJavaScriptPreprocessingFile. Safari runs
//       it INSIDE the page being shared, before the sheet opens, and hands its result
//       to the sheet as `preprocessingResults` — `{ title, url, readMode }`. It has to
//       be a self-contained file Safari can evaluate (no Metro, no imports) whose
//       `ExtensionPreprocessingJS` is a GLOBAL-object property, hence the `var`.
//
//   apps/bracemark-expo/src/features/capture/reader-capture-script.generated.ts
//       The same bundle as a string, for expo's capture screen to inject into its
//       WebView; it posts the copy back through `window.ReactNativeWebView`.
//
// Both are CHECKED IN and generated, never hand-edited. Each carries a hash of the
// sources it was built from, and web-react's reader-capture-generated.spec.ts fails
// when they drift — in the package where the converter lives, so editing it fails
// beside the edit (the contract-vectors arrangement: tools/scripts/
// generate-contract-vectors.ts). docs/link-extraction-keep.md, _expo_.
//
//   npx tsx tools/scripts/generate-reader-capture.ts

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

// What the bundle's behaviour depends on. The spec hashes the same list.
export const READER_CAPTURE_HASH_INPUTS = [
  'packages/web-react/src/lib/reader-doc-from-page.ts',
  'packages/shared/src/reader/reader-doc.ts',
  'packages/shared/src/reader/reader-doc-core.ts',
  'node_modules/@mozilla/readability/package.json',
  'tools/scripts/generate-reader-capture.ts',
];

export function readerCaptureSourceHash(root = ROOT): string {
  const hash = createHash('sha256');
  for (const input of READER_CAPTURE_HASH_INPUTS) {
    hash.update(input);
    hash.update(readFileSync(join(root, input)));
  }
  return hash.digest('hex').slice(0, 16);
}

// The copy is handed across a process boundary (Safari → the share extension, or the
// WebView → JS); past this many characters of JSON it is dropped rather than sent.
// Far above any article (READER_DOC_MAX_CHARS bounds the text at 1M), it only binds
// on a pathological page — and the share extension has ~120 MB to work in.
const MAX_PAYLOAD_CHARS = 3_000_000;

const ENTRY = `
import { readerDocFromPage } from '@stxapps/web-react/lib/reader-doc-from-page';
globalThis.__bracemarkReaderDoc = function () {
  try {
    var doc = readerDocFromPage(document);
    if (doc && JSON.stringify(doc).length > ${MAX_PAYLOAD_CHARS}) return null;
    return doc;
  } catch (e) {
    return null;
  }
};
`;

async function bundle(): Promise<string> {
  const result = await build({
    stdin: {
      contents: ENTRY,
      resolveDir: ROOT,
      loader: 'ts',
      sourcefile: 'reader-capture-entry.ts',
    },
    bundle: true,
    format: 'iife',
    platform: 'browser',
    // The iOS deployment target is 26 (app.config.ts) and the WebView is the
    // system's; es2020 is comfortably inside both.
    target: 'es2020',
    minify: true,
    write: false,
    legalComments: 'eof',
  });
  return result.outputFiles[0].text.trim();
}

export async function renderReaderCapture(): Promise<{
  preprocessing: string;
  captureModule: string;
}> {
  const hash = readerCaptureSourceHash();
  const code = await bundle();
  const banner = `GENERATED by tools/scripts/generate-reader-capture.ts — do not edit. source-hash: ${hash}`;

  const preprocessing = `// ${banner}
//
// The iOS share extension's NSExtensionJavaScriptPreprocessingFile (wired by
// expo-share-extension's \`preprocessingFile\` option in app.config.ts). Safari runs it
// inside the shared page; the result lands on the sheet's RN root as
// \`preprocessingResults\` and is read by src/features/share/share-url.ts.
// docs/share-sheet.md, _what the sheet does and doesn't do_.
/* eslint-disable */
${code}
var ExtensionPreprocessingJS = {
  run: function (args) {
    var readMode = null;
    try {
      readMode = globalThis.__bracemarkReaderDoc();
    } catch (e) {}
    args.completionFunction({ title: document.title, url: window.location.href, readMode: readMode });
  },
};
`;

  const injected = `${code}
;(function () {
  var doc = null;
  try {
    doc = globalThis.__bracemarkReaderDoc();
  } catch (e) {}
  window.ReactNativeWebView.postMessage(JSON.stringify({ type: 'bracemark-read-mode', doc: doc }));
})();
true;`;

  const captureModule = `// ${banner}
/* eslint-disable */
// prettier-ignore
export const READER_CAPTURE_SOURCE_HASH = '${hash}';

// Inject into a WebView showing the page; it posts \`{ type: 'bracemark-read-mode', doc }\`
// back through window.ReactNativeWebView, \`doc\` null when the page isn't an article.
// prettier-ignore
export const READER_CAPTURE_SCRIPT: string = ${JSON.stringify(injected)};
`;

  return { preprocessing, captureModule };
}

export const PREPROCESSING_PATH = 'apps/bracemark-expo/share-extension/preprocessing.js';
export const CAPTURE_MODULE_PATH =
  'apps/bracemark-expo/src/features/capture/reader-capture-script.generated.ts';

async function main(): Promise<void> {
  const { preprocessing, captureModule } = await renderReaderCapture();
  writeFileSync(join(ROOT, PREPROCESSING_PATH), preprocessing);
  writeFileSync(join(ROOT, CAPTURE_MODULE_PATH), captureModule);
  console.log(`wrote ${PREPROCESSING_PATH} and ${CAPTURE_MODULE_PATH}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  void main();
}
