import { isProbablyReaderable, Readability } from '@mozilla/readability';

import {
  isReaderHref,
  READER_DOC_MAX_BLOCKS,
  READER_DOC_MAX_CHARS,
  READER_DOC_VERSION,
  type ReaderBlock,
  type ReaderDoc,
  type ReaderRun,
} from '@stxapps/shared';

// The read-mode capture — ONE converter for every client that captures from a live
// page, run INSIDE that page, because Readability needs a DOM:
//
//   - the browser extension injects it into the active tab as a bundled unlisted
//     script (apps/bracemark-extension entrypoints/read-mode.ts);
//   - the iOS share extension's preprocessing file runs it inside the Safari page
//     being shared, and expo's capture screen injects the same bundle into its
//     WebView (both generated by tools/scripts/generate-reader-capture.ts).
//
// One copy, so a page reads the same whichever client took it — a tier upgrade or a
// second capture is an improvement, never a different text. It lives in web-react
// (platform:web) because it needs DOM types and Readability, and it is reached through
// its own SUBPATH export, never the barrel: each caller bundles it into a script that
// runs inside a stranger's page, and the barrel would drag Dexie and the sync engine
// in with it (docs/architecture.md, _the barrel is the API — except where a barrel is
// the cost_).
//
// Two steps. READABILITY finds the article in a CLONE of the live document (it mutates
// what it's given, and this is the page the user is looking at). Then THIS file turns
// the article's HTML into `ReaderDoc` blocks — plain strings with marks — so no markup
// the page wrote survives into storage (shared reader/reader-doc.ts says why that is
// the whole point). The article HTML is parsed with DOMParser, which builds an inert
// document: nothing in it runs or loads.
//
// Returns null when the page isn't an article (Readability's own pre-check, then its
// parse) — a caller records that as a settled `permanent`, not as a failure to retry.

// Elements whose content is never article text, even inside what Readability kept.
const SKIP = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEMPLATE', 'IFRAME', 'OBJECT', 'EMBED']);
const SKIP_SVG = 'svg';
const HEADINGS: Record<string, number> = { H1: 1, H2: 2, H3: 3, H4: 4, H5: 5, H6: 6 };
// Block-level elements: entering one closes the paragraph being collected.
const BLOCKS = new Set([
  'ADDRESS',
  'ARTICLE',
  'ASIDE',
  'BLOCKQUOTE',
  'DD',
  'DETAILS',
  'DIV',
  'DL',
  'DT',
  'FIELDSET',
  'FIGCAPTION',
  'FIGURE',
  'FOOTER',
  'FORM',
  'H1',
  'H2',
  'H3',
  'H4',
  'H5',
  'H6',
  'HEADER',
  'HR',
  'LI',
  'MAIN',
  'NAV',
  'OL',
  'P',
  'PICTURE',
  'PRE',
  'SECTION',
  'SUMMARY',
  'TABLE',
  'TBODY',
  'TD',
  'TFOOT',
  'TH',
  'THEAD',
  'TR',
  'UL',
]);

type Marks = Pick<ReaderRun, 'bold' | 'italic' | 'code' | 'href'>;
// A block before it is numbered. Spelled out rather than `Omit<ReaderBlock, 'id'>`:
// the schema is a looseObject, and Omit over its index signature keeps only that.
type BlockBody = Pick<ReaderBlock, 'kind' | 'level' | 'ordered' | 'runs' | 'text'>;
type BlockShape = Omit<BlockBody, 'runs'>;

class Builder {
  readonly blocks: ReaderBlock[] = [];
  private chars = 0;
  // The inline runs of the block being collected, and what kind it becomes when closed.
  private runs: ReaderRun[] = [];
  private pending: BlockShape = { kind: 'paragraph' };

  get full(): boolean {
    return this.blocks.length >= READER_DOC_MAX_BLOCKS || this.chars >= READER_DOC_MAX_CHARS;
  }

  // Start collecting inline content for a block of this shape (closing any open one).
  open(shape: BlockShape): void {
    this.close();
    this.pending = shape;
  }

  text(raw: string, marks: Marks, preserve = false): void {
    const text = preserve ? raw : raw.replace(/\s+/g, ' ');
    if (text === '') return;
    const last = this.runs[this.runs.length - 1];
    if (last && sameMarks(last, marks)) {
      last.text += text;
      return;
    }
    this.runs.push({ text, ...definedMarks(marks) });
  }

  // Close the open block: trim its edges, drop it if nothing is left, number it.
  close(): void {
    const runs = trimRuns(this.runs);
    this.runs = [];
    const shape = this.pending;
    this.pending = { kind: 'paragraph' };
    if (runs.length === 0) return;
    this.push({ ...shape, runs });
  }

  push(block: BlockBody): void {
    if (this.full) return;
    this.chars += (block.text ?? '').length;
    for (const run of block.runs ?? []) this.chars += run.text.length;
    this.blocks.push({ id: `b${this.blocks.length}`, ...block });
  }
}

function definedMarks(marks: Marks): Marks {
  const out: Marks = {};
  if (marks.bold) out.bold = true;
  if (marks.italic) out.italic = true;
  if (marks.code) out.code = true;
  if (marks.href) out.href = marks.href;
  return out;
}

function sameMarks(run: ReaderRun, marks: Marks): boolean {
  return (
    !!run.bold === !!marks.bold &&
    !!run.italic === !!marks.italic &&
    !!run.code === !!marks.code &&
    run.href === marks.href
  );
}

// Trim whitespace off the block's two ends (inside runs, a collapsed space between
// words is content) and drop runs that end up empty.
function trimRuns(runs: ReaderRun[]): ReaderRun[] {
  const out = runs.map((run) => ({ ...run }));
  while (out.length > 0) {
    out[0].text = out[0].text.replace(/^\s+/, '');
    if (out[0].text !== '') break;
    out.shift();
  }
  while (out.length > 0) {
    const last = out[out.length - 1];
    last.text = last.text.replace(/\s+$/, '');
    if (last.text !== '') break;
    out.pop();
  }
  return out;
}

function inlineMarks(el: Element, marks: Marks): Marks {
  switch (el.tagName) {
    case 'B':
    case 'STRONG':
      return { ...marks, bold: true };
    case 'I':
    case 'EM':
    case 'CITE':
      return { ...marks, italic: true };
    case 'CODE':
    case 'KBD':
    case 'SAMP':
      return { ...marks, code: true };
    case 'A': {
      // Readability has already made relative hrefs absolute against the page.
      const href = el.getAttribute('href') ?? undefined;
      return { ...marks, href: isReaderHref(href) ? href : undefined };
    }
    default:
      return marks;
  }
}

function captionOf(figure: Element): ReaderRun[] {
  const caption = figure.querySelector('figcaption');
  if (!caption) return [];
  const builder = new Builder();
  builder.open({ kind: 'paragraph' });
  walkInline(caption, builder, {});
  builder.close();
  return builder.blocks[0]?.runs ?? [];
}

function walkInline(node: Node, builder: Builder, marks: Marks, preserve = false): void {
  for (const child of Array.from(node.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) {
      builder.text(child.textContent ?? '', marks, preserve);
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      const el = child as Element;
      if (SKIP.has(el.tagName) || el.localName === SKIP_SVG) continue;
      if (el.tagName === 'BR') builder.text('\n', marks, true);
      else walkInline(el, builder, inlineMarks(el, marks), preserve);
    }
  }
}

// Walk a container's children: inline content accumulates into the open block, and a
// block-level child closes it and is handled by kind.
function walkBlocks(node: Node, builder: Builder, ctx: { quote: boolean; depth: number }): void {
  const paragraphKind = ctx.quote ? 'quote' : 'paragraph';
  builder.open({ kind: paragraphKind });
  for (const child of Array.from(node.childNodes)) {
    if (builder.full) return;
    if (child.nodeType === Node.TEXT_NODE) {
      builder.text(child.textContent ?? '', {});
      continue;
    }
    if (child.nodeType !== Node.ELEMENT_NODE) continue;
    const el = child as Element;
    if (SKIP.has(el.tagName) || el.localName === SKIP_SVG) continue;
    if (!BLOCKS.has(el.tagName) && el.tagName !== 'IMG') {
      if (el.tagName === 'BR') builder.text('\n', {}, true);
      else walkInline(el, builder, inlineMarks(el, {}));
      continue;
    }

    builder.close();
    const level = HEADINGS[el.tagName];
    if (level !== undefined) {
      builder.open({ kind: 'heading', level });
      walkInline(el, builder, {});
    } else if (el.tagName === 'P') {
      builder.open({ kind: paragraphKind });
      walkInline(el, builder, {});
    } else if (el.tagName === 'BLOCKQUOTE') {
      walkBlocks(el, builder, { ...ctx, quote: true });
    } else if (el.tagName === 'UL' || el.tagName === 'OL') {
      const ordered = el.tagName === 'OL';
      for (const item of Array.from(el.children)) {
        if (item.tagName !== 'LI') continue;
        walkListItem(item, builder, { ordered, depth: ctx.depth });
      }
    } else if (el.tagName === 'PRE') {
      const text = (el.textContent ?? '').replace(/^\n+|\s+$/g, '');
      if (text !== '') builder.push({ kind: 'code', text });
    } else if (el.tagName === 'HR') {
      builder.push({ kind: 'rule' });
    } else if (el.tagName === 'IMG' || el.tagName === 'FIGURE' || el.tagName === 'PICTURE') {
      // The copy carries no image bytes and never a remote URL (rendering one would be
      // a request to the site per view): a placeholder with what words it had. A
      // figure wrapping something other than an image (a code listing, a quote) is
      // walked as a container instead.
      const img = el.tagName === 'IMG' ? el : el.querySelector('img');
      if (img) {
        const alt = (img.getAttribute('alt') ?? '').trim();
        const runs = el.tagName === 'FIGURE' ? captionOf(el) : [];
        if (alt !== '' || runs.length > 0) {
          builder.push({ kind: 'figure', ...(alt ? { text: alt } : {}), runs });
        }
      } else {
        walkBlocks(el, builder, ctx);
      }
    } else if (el.tagName === 'TABLE') {
      // v1 has no table block: one paragraph per row, cells joined. Readable, not
      // tabular — a `table` kind is the obvious next block, and older readers skip it.
      for (const row of Array.from(el.querySelectorAll('tr'))) {
        builder.open({ kind: paragraphKind });
        Array.from(row.children).forEach((cell, i) => {
          if (i > 0) builder.text(' · ', {}, true);
          walkInline(cell, builder, {});
        });
        builder.close();
      }
    } else {
      walkBlocks(el, builder, ctx);
    }
    builder.open({ kind: paragraphKind });
  }
  builder.close();
}

function walkListItem(
  item: Element,
  builder: Builder,
  list: { ordered: boolean; depth: number },
): void {
  builder.open({ kind: 'listItem', ordered: list.ordered, level: list.depth });
  for (const child of Array.from(item.childNodes)) {
    if (child.nodeType === Node.ELEMENT_NODE) {
      const el = child as Element;
      if (el.tagName === 'UL' || el.tagName === 'OL') {
        builder.close();
        const ordered = el.tagName === 'OL';
        for (const nested of Array.from(el.children)) {
          if (nested.tagName === 'LI') {
            walkListItem(nested, builder, { ordered, depth: list.depth + 1 });
          }
        }
        // Text after a nested list continues the item, as a further item line.
        builder.open({ kind: 'listItem', ordered: list.ordered, level: list.depth });
        continue;
      }
      if (SKIP.has(el.tagName) || el.localName === SKIP_SVG) continue;
      if (el.tagName === 'BR') builder.text('\n', {}, true);
      else walkInline(el, builder, inlineMarks(el, {}));
    } else if (child.nodeType === Node.TEXT_NODE) {
      builder.text(child.textContent ?? '', {});
    }
  }
  builder.close();
}

const optional = (value: string | null | undefined): string | undefined => {
  const trimmed = value?.trim();
  return trimmed ? trimmed : undefined;
};

export function readerDocFromPage(page: Document, now = Date.now()): ReaderDoc | null {
  if (!isProbablyReaderable(page)) return null;

  const article = new Readability(page.cloneNode(true) as Document).parse();
  if (!article?.content) return null;

  const parsed = new DOMParser().parseFromString(article.content, 'text/html');
  const builder = new Builder();
  walkBlocks(parsed.body, builder, { quote: false, depth: 0 });
  if (builder.blocks.length === 0) return null;

  const doc: ReaderDoc = {
    version: READER_DOC_VERSION,
    capturedAt: now,
    sourceUrl: page.URL,
    blocks: builder.blocks,
  };
  const fields = {
    title: optional(article.title),
    byline: optional(article.byline),
    siteName: optional(article.siteName),
    excerpt: optional(article.excerpt),
    publishedTime: optional(article.publishedTime),
    lang: optional(article.lang),
    dir: optional(article.dir),
  };
  for (const [key, value] of Object.entries(fields)) {
    if (value !== undefined) (doc as Record<string, unknown>)[key] = value;
  }
  return doc;
}
