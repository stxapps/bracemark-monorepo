import { isProbablyReaderable, Readability } from '@mozilla/readability';

import type { ReaderDoc, ReaderImageSource } from '@stxapps/shared';
// Values from zod-free subpaths, types from the barrel (erased at build): this file is
// bundled into scripts that run inside a page, and the barrel would carry zod and every
// schema in the package with it (reader-doc-core.ts says so too).
import {
  readerCaptureFromArticle,
  readerDocFromArticle,
} from '@stxapps/shared/reader/reader-doc-from-dom';

// The read-mode capture from a LIVE page, run INSIDE that page, because Readability
// needs a DOM:
//
//   - the browser extension injects it into the active tab as a bundled unlisted
//     script (apps/bracemark-extension entrypoints/read-mode.ts);
//   - the iOS share extension's preprocessing file runs it inside the Safari page
//     being shared, and expo's capture screen injects the same bundle into its
//     WebView (both generated by tools/scripts/generate-reader-capture.ts).
//
// It lives in web-react (platform:web) because it needs the browser's DOM — the live
// `document` and DOMParser — and it is reached through its own SUBPATH export, never
// the barrel: each caller bundles it into a script that runs inside a stranger's page,
// and the barrel would drag Dexie and the sync engine in with it (docs/architecture.md,
// _the barrel is the API — except where a barrel is the cost_).
//
// Two steps. READABILITY finds the article in a CLONE of the live document (it mutates
// what it's given, and this is the page the user is looking at). Then the shared
// walker, `readerDocFromArticle` (@stxapps/shared reader/reader-doc-from-dom.ts),
// turns the article's HTML into `ReaderDoc` blocks. The walker is the part that decides
// what a copy SAYS, and bracemark-extractor runs the same one over linkedom
// (its lib/read-mode.ts), so a page reads the same from every tier. The article HTML
// is parsed with DOMParser, which builds an inert document: nothing in it runs or
// loads.
//
// Returns null when the page isn't an article (Readability's own pre-check, then its
// parse) — a caller records that as a settled `permanent`, not as a failure to retry.
export function readerDocFromPage(page: Document, now = Date.now()): ReaderDoc | null {
  if (!isProbablyReaderable(page)) return null;

  const article = new Readability(page.cloneNode(true) as Document).parse();
  if (!article?.content) return null;

  const parsed = new DOMParser().parseFromString(article.content, 'text/html');
  return readerDocFromArticle(parsed.body, article, page.URL, now);
}

// The same capture with the article's images: the document, whose figures carry a key
// each, and BESIDE it the address every key's bytes are at. The caller fetches what it
// can and settles the document with `applyReaderImages` (@stxapps/shared
// reader/reader-images.ts) before storing it; the addresses are for that fetch and are
// never stored. Null as above.
export function readerCaptureFromPage(
  page: Document,
  now = Date.now(),
): { doc: ReaderDoc; images: ReaderImageSource[] } | null {
  if (!isProbablyReaderable(page)) return null;

  const article = new Readability(page.cloneNode(true) as Document).parse();
  if (!article?.content) return null;

  const parsed = new DOMParser().parseFromString(article.content, 'text/html');
  return readerCaptureFromArticle(parsed.body, article, page.URL, now);
}
