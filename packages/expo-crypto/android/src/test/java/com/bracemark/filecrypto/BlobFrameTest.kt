package com.bracemark.filecrypto

import java.io.File
import java.io.IOException
import javax.crypto.Cipher
import javax.crypto.spec.GCMParameterSpec
import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

// Until this suite existed, the ONLY thing asserting that Kotlin writes the same
// frame the browser reads was the comment at the top of BlobFrame.kt saying so —
// the constants and the AAD here are a hand-copy of @stxapps/shared
// (crypto/params.ts, crypto/blob-aad.ts), nothing links them, and a divergence
// is silent right up until a user opens a synced image on the other platform and
// it will not decrypt.
//
// It runs on the plain JVM (`src/test`, javax.crypto + java.io) — no emulator,
// no app, milliseconds. That is only possible because the framing lives outside
// the expo Module class; see BlobFrame.kt's header.
//
// The vectors are READ FROM DISK rather than pasted here, from the same JSON the
// Swift twin reads, so this suite cannot drift from the one web-crypto asserts
// (packages/shared/src/crypto/contract-vectors.json — regenerated by
// tools/scripts/generate-contract-vectors.ts, guarded by contract-vectors.spec.ts).
class BlobFrameTest {
  @get:Rule val tmp = TemporaryFolder()

  private val vector: JSONObject by lazy {
    // Gradle's working directory for unit tests is the module dir, but that is
    // not worth depending on — walk up to the workspace root instead, so this
    // passes whether it is driven by the app's gradle build or this module's.
    var dir: File? = File(System.getProperty("user.dir") ?: ".")
    while (dir != null) {
      val candidate = File(dir, "packages/shared/src/crypto/contract-vectors.json")
      if (candidate.isFile) return@lazy JSONObject(candidate.readText())
      dir = dir.parentFile
    }
    throw IllegalStateException("contract-vectors.json not found above ${System.getProperty("user.dir")}")
  }

  private val blob: JSONObject get() = vector.getJSONObject("blob")
  private val path: String get() = blob.getString("path")
  private fun key() = BlobFrame.secretKey(vector.getString("encryptionKeyHex"))

  private fun hex(s: String) = ByteArray(s.length / 2) {
    ((Character.digit(s[it * 2], 16) shl 4) or Character.digit(s[it * 2 + 1], 16)).toByte()
  }

  private fun fileOf(name: String, bytes: ByteArray) =
    File(tmp.root, name).also { it.writeBytes(bytes) }

  // THE cross-platform assertion: bytes sealed by Web Crypto, opened here, under
  // the path they were sealed for. Everything else in this file is a property of
  // this implementation; this one is the contract.
  @Test
  fun `decrypts the golden v1 frame under its path`() {
    val input = fileOf("in.enc", hex(blob.getString("packedHex")))
    val output = File(tmp.root, "out.txt")

    BlobFrame.decryptFile(input, output, key(), path)

    assertEquals(blob.getString("plaintext"), output.readText())
  }

  // What the AAD exists for: the same bytes fetched for another path do not open, and
  // leave nothing behind.
  @Test
  fun `refuses the golden v1 frame under another path`() {
    for (other in listOf("links/other.enc", "files/contract-vector.enc", "$path ")) {
      val input = fileOf("in.enc", hex(blob.getString("packedHex")))
      val output = File(tmp.root, "out.txt")

      assertThrows(BlobFrameError.DecryptionFailed::class.java) {
        BlobFrame.decryptFile(input, output, key(), other)
      }
      assertFalse("plaintext left at the output path", output.exists())
    }
  }

  // The AAD is the hand-copied half of the contract, so it gets its own check:
  // the bytes, and a reseal under the vector's own IV that must reproduce the
  // golden frame byte for byte.
  @Test
  fun `builds the contract aad and reseals the golden frame`() {
    val aad = BlobFrame.aad(path)
    assertArrayEquals(hex(blob.getString("aadHex")), aad)

    val iv = hex(blob.getString("ivHex"))
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.ENCRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, iv))
    cipher.updateAAD(aad)
    val sealed = cipher.doFinal(blob.getString("plaintext").toByteArray())
    assertArrayEquals(
      hex(blob.getString("packedHex")),
      byteArrayOf(BLOB_FORMAT_V1.toByte()) + iv + sealed,
    )
  }

  // A frame sealed without the path — what a pre-binding build wrote — fails
  // the tag, and leaves nothing behind.
  @Test
  fun `refuses a frame sealed without the path`() {
    val iv = hex(blob.getString("ivHex"))
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.ENCRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, iv))
    val unbound = byteArrayOf(BLOB_FORMAT_V1.toByte()) + iv + cipher.doFinal(blob.getString("plaintext").toByteArray())
    val input = fileOf("unbound.enc", unbound)
    val output = File(tmp.root, "out.txt")

    assertThrows(BlobFrameError.DecryptionFailed::class.java) {
      BlobFrame.decryptFile(input, output, key(), path)
    }
    assertFalse("plaintext left at the output path", output.exists())
  }

  // The reverse direction cannot assert bytes — the IV is minted per call — so
  // it pins the frame's SHAPE, which is the part a JS reader depends on.
  @Test
  fun `writes a v1 frame the contract describes`() {
    val plaintext = blob.getString("plaintext").toByteArray()
    val input = fileOf("in.txt", plaintext)
    val output = File(tmp.root, "out.enc")

    BlobFrame.encryptFile(input, output, key(), path)

    val framed = output.readBytes()
    assertEquals(BLOB_FORMAT_V1, framed[0].toInt() and 0xff)
    assertEquals(1 + IV_BYTES + plaintext.size + TAG_BYTES, framed.size)
  }

  @Test
  fun `round trips its own output`() {
    val plaintext = ByteArray(200_000) { (it % 251).toByte() } // > the 64 KiB copy buffer
    val input = fileOf("in.bin", plaintext)
    val sealed = File(tmp.root, "mid.enc")
    val output = File(tmp.root, "out.bin")

    BlobFrame.encryptFile(input, sealed, key(), path)
    BlobFrame.decryptFile(sealed, output, key(), path)

    assertArrayEquals(plaintext, output.readBytes())
  }

  // A wrong version byte must be rejected as a version problem. Sliced blindly
  // instead, an unknown frame would hand GCM a shifted IV and surface as
  // "tampered", sending the reader after a corruption bug that is not there.
  @Test
  fun `rejects an unknown format version`() {
    val framed = hex(blob.getString("packedHex")).also { it[0] = 0x02 }
    val input = fileOf("v2.enc", framed)

    val err = assertThrows(BlobFrameError.UnknownFormat::class.java) {
      BlobFrame.decryptFile(input, File(tmp.root, "out"), key(), path)
    }
    assertEquals(2, err.version)
  }

  @Test
  fun `rejects a blob too short to hold a frame`() {
    val input = fileOf("short.enc", hex(blob.getString("packedHex")).copyOfRange(0, 8))

    assertThrows(BlobFrameError::class.java) {
      BlobFrame.decryptFile(input, File(tmp.root, "out"), key(), path)
    }
  }

  // GCM authenticates; a flipped bit in the tag must fail rather than yield
  // plaintext. This is the whole reason the format carries a tag at all.
  @Test
  fun `rejects a tampered tag`() {
    val framed = hex(blob.getString("packedHex"))
    framed[framed.size - 1] = (framed[framed.size - 1].toInt() xor 0x01).toByte()
    val input = fileOf("bad-tag.enc", framed)

    assertThrows(BlobFrameError.DecryptionFailed::class.java) {
      BlobFrame.decryptFile(input, File(tmp.root, "out"), key(), path)
    }
  }

  @Test
  fun `rejects a wrong key`() {
    val input = fileOf("in.enc", hex(blob.getString("packedHex")))
    val wrong = BlobFrame.secretKey("00".repeat(KEY_BYTES))

    assertThrows(BlobFrameError.DecryptionFailed::class.java) {
      BlobFrame.decryptFile(input, File(tmp.root, "out"), wrong, path)
    }
  }

  // The key crosses the JS boundary as hex (file-crypto.ts). A short or
  // non-hex string must be refused here rather than silently padded into a key
  // that decrypts nothing.
  @Test
  fun `refuses a key that is not 32 bytes of hex`() {
    assertThrows(BlobFrameError.InvalidKey::class.java) { BlobFrame.secretKey("00".repeat(31)) }
    assertThrows(BlobFrameError.InvalidKey::class.java) { BlobFrame.secretKey("zz".repeat(32)) }
  }

  // The atomic-write claim in BlobFrame.kt: GCM only authenticates at the END of
  // the stream, so a failed tag must leave NOTHING behind — not a partial
  // plaintext at the output path, and not the temp file either. A consumer that
  // found either would be reading unauthenticated bytes.
  @Test
  fun `leaves no output and no temp file when authentication fails`() {
    val framed = hex(blob.getString("packedHex"))
    framed[framed.size - 1] = (framed[framed.size - 1].toInt() xor 0x01).toByte()
    val input = fileOf("bad-tag.enc", framed)
    val output = File(tmp.root, "out.txt")

    assertThrows(BlobFrameError.DecryptionFailed::class.java) {
      BlobFrame.decryptFile(input, output, key(), path)
    }

    assertFalse("plaintext left at the output path", output.exists())
    assertFalse("temp file left behind", File(tmp.root, "out.txt.tmp").exists())
  }

  // A failure to WRITE is not a failure to decrypt. The two were one catch once,
  // so a full disk reached JS as "tampered file or wrong key" — the message that
  // sends a reader after a corruption bug. The output's parent here is a regular
  // file, the cheapest write that cannot succeed.
  @Test
  fun `reports an unwritable output as an io error, not a decryption failure`() {
    val input = fileOf("in.enc", hex(blob.getString("packedHex")))
    val notADirectory = fileOf("plain-file", byteArrayOf(0))

    assertThrows(IOException::class.java) {
      BlobFrame.decryptFile(input, File(notADirectory, "out.txt"), key(), path)
    }
  }

  // expo-file-system hands out file:// URIs, expo-crypto's own callers hand out
  // plain paths; both reach the same file.
  //
  // The uri is built by hand rather than with `file.toURI()`, which looks like
  // the obvious spelling and is the wrong input: Java emits the single-slash
  // form (`file:/var/...`), expo-file-system emits `file:///var/...`, and
  // `resolve` tests for `file://`. Written the obvious way this test fails
  // against a path production never sends.
  @Test
  fun `resolves file uris and plain paths alike`() {
    val file = fileOf("x.bin", byteArrayOf(1, 2, 3))

    assertEquals(file, BlobFrame.resolve(file.absolutePath))
    assertEquals(file, BlobFrame.resolve("file://" + file.absolutePath))
  }
}
