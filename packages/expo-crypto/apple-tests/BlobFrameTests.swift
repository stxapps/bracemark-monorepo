import CryptoKit
import Foundation
import XCTest

@testable import BracemarkBlobFrame

// Until this suite existed, the ONLY thing asserting that Swift writes the same
// frame the browser reads was the comment at the top of BlobFrame.swift saying
// so — the constants and the AAD there are a hand-copy of @stxapps/shared
// (crypto/params.ts, crypto/blob-aad.ts), nothing links them, and a divergence
// is silent right up until a user opens a synced image on the other platform
// and it will not decrypt.
//
// It runs on the host (`swift test`) — no simulator, no app — which is only
// possible because the framing lives outside the expo Module class.
//
// The vectors are READ FROM DISK rather than pasted here, from the same JSON the
// Kotlin twin reads, so this suite cannot drift from the one web-crypto asserts
// (packages/shared/src/crypto/contract-vectors.json — regenerated by
// tools/scripts/generate-contract-vectors.ts, guarded by contract-vectors.spec.ts).
final class BlobFrameTests: XCTestCase {
  private struct Vector: Decodable {
    struct Blob: Decodable {
      let path: String
      let ivHex: String
      let plaintext: String
      let aadHex: String
      let packedHex: String
    }
    let encryptionKeyHex: String
    let blob: Blob
  }

  private static let vector: Vector = {
    // Walk up to the workspace root rather than depending on swift test's
    // working directory.
    var dir = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    while dir.path != "/" {
      let candidate = dir.appendingPathComponent("packages/shared/src/crypto/contract-vectors.json")
      if FileManager.default.fileExists(atPath: candidate.path) {
        // swiftlint:disable:next force_try
        return try! JSONDecoder().decode(Vector.self, from: Data(contentsOf: candidate))
      }
      dir = dir.deletingLastPathComponent()
    }
    fatalError("contract-vectors.json not found above \(#filePath)")
  }()

  private var vector: Vector { Self.vector }
  private var path: String { vector.blob.path }
  private func key() throws -> SymmetricKey {
    try BlobFrame.symmetricKey(vector.encryptionKeyHex)
  }
  private func packed() throws -> Data {
    try XCTUnwrap(BlobFrame.hexData(vector.blob.packedHex))
  }

  private func tempFile(_ name: String, _ bytes: Data) throws -> String {
    let url = FileManager.default.temporaryDirectory
      .appendingPathComponent(UUID().uuidString, isDirectory: true)
      .appendingPathComponent(name)
    try FileManager.default.createDirectory(
      at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try bytes.write(to: url)
    return url.path
  }

  // THE cross-platform assertion: bytes sealed by Web Crypto, opened here, under
  // the path they were sealed for. Everything else in this file is a property of
  // this implementation; this one is the contract.
  func testOpensTheGoldenV1FrameUnderItsPath() throws {
    let plaintext = try BlobFrame.open(packed(), using: key(), path: path)

    XCTAssertEqual(String(decoding: plaintext, as: UTF8.self), vector.blob.plaintext)
  }

  // What the AAD exists for: the same bytes served under another path do not open.
  func testRefusesTheGoldenV1FrameUnderAnotherPath() throws {
    for other in ["links/other.enc", "files/contract-vector.enc", path + " "] {
      XCTAssertThrowsError(try BlobFrame.open(packed(), using: key(), path: other)) { error in
        XCTAssertEqual(error as? BlobFrameError, .decryptionFailed)
      }
    }
  }

  // The AAD is the hand-copied half of the contract, so it gets its own check:
  // the bytes, and a reseal under the vector's own nonce that must reproduce the
  // golden frame byte for byte.
  func testBuildsTheContractAadAndResealsTheGoldenFrame() throws {
    let aad = BlobFrame.aad(path: path)
    XCTAssertEqual(aad, try XCTUnwrap(BlobFrame.hexData(vector.blob.aadHex)))

    let nonce = try AES.GCM.Nonce(data: XCTUnwrap(BlobFrame.hexData(vector.blob.ivHex)))
    let sealed = try AES.GCM.seal(
      Data(vector.blob.plaintext.utf8), using: key(), nonce: nonce, authenticating: aad)
    var framed = Data([BlobFrame.formatV1])
    framed.append(try XCTUnwrap(sealed.combined))
    XCTAssertEqual(framed, try packed())
  }

  // A frame sealed without the path — what a pre-binding build wrote — fails
  // the tag.
  func testRefusesAFrameSealedWithoutThePath() throws {
    let nonce = try AES.GCM.Nonce(data: XCTUnwrap(BlobFrame.hexData(vector.blob.ivHex)))
    let sealed = try AES.GCM.seal(Data(vector.blob.plaintext.utf8), using: key(), nonce: nonce)
    var unbound = Data([BlobFrame.formatV1])
    unbound.append(try XCTUnwrap(sealed.combined))

    XCTAssertThrowsError(try BlobFrame.open(unbound, using: key(), path: path)) { error in
      XCTAssertEqual(error as? BlobFrameError, .decryptionFailed)
    }
  }

  // The reverse direction cannot assert bytes — the nonce is minted per call —
  // so it pins the frame's SHAPE, which is the part a JS reader depends on.
  func testSealsAV1FrameTheContractDescribes() throws {
    let plaintext = Data(vector.blob.plaintext.utf8)

    let framed = try BlobFrame.seal(plaintext, using: key(), path: path)

    XCTAssertEqual(framed.first, BlobFrame.formatV1)
    XCTAssertEqual(
      framed.count, 1 + BlobFrame.ivBytes + plaintext.count + BlobFrame.tagBytes)
  }

  func testRoundTripsItsOwnOutput() throws {
    let plaintext = Data((0..<200_000).map { UInt8($0 % 251) })

    let framed = try BlobFrame.seal(plaintext, using: key(), path: path)

    XCTAssertEqual(try BlobFrame.open(framed, using: key(), path: path), plaintext)
  }

  // A wrong version byte must be rejected as a version problem. Sliced blindly
  // instead, an unknown frame would hand GCM a shifted nonce and surface as
  // "tampered", sending the reader after a corruption bug that is not there.
  func testRejectsAnUnknownFormatVersion() throws {
    var framed = try packed()
    framed[framed.startIndex] = 0x02

    XCTAssertThrowsError(try BlobFrame.open(framed, using: key(), path: path)) { error in
      XCTAssertEqual(error as? BlobFrameError, .unknownFormat(0x02))
    }
  }

  func testRejectsABlobTooShortToHoldAFrame() throws {
    let framed = try packed().prefix(8)

    XCTAssertThrowsError(try BlobFrame.open(Data(framed), using: key(), path: path)) { error in
      XCTAssertEqual(error as? BlobFrameError, .truncated)
    }
  }

  // GCM authenticates; a flipped bit in the tag must fail rather than yield
  // plaintext. This is the whole reason the format carries a tag at all.
  func testRejectsATamperedTag() throws {
    var framed = try packed()
    framed[framed.index(before: framed.endIndex)] ^= 0x01

    XCTAssertThrowsError(try BlobFrame.open(framed, using: key(), path: path)) { error in
      XCTAssertEqual(error as? BlobFrameError, .decryptionFailed)
    }
  }

  func testRejectsAWrongKey() throws {
    let wrong = try BlobFrame.symmetricKey(String(repeating: "00", count: BlobFrame.keyBytes))

    XCTAssertThrowsError(try BlobFrame.open(packed(), using: wrong, path: path)) { error in
      XCTAssertEqual(error as? BlobFrameError, .decryptionFailed)
    }
  }

  // The key crosses the JS boundary as hex (file-crypto.ts). A short or non-hex
  // string must be refused here rather than silently truncated into a key that
  // decrypts nothing.
  func testRefusesAKeyThatIsNot32BytesOfHex() {
    XCTAssertThrowsError(try BlobFrame.symmetricKey(String(repeating: "00", count: 31)))
    XCTAssertThrowsError(try BlobFrame.symmetricKey(String(repeating: "zz", count: 32)))
  }

  // Both halves of the file API, against the real filesystem — the path the
  // native module actually takes.
  func testEncryptsAndDecryptsThroughTheFileAPI() throws {
    let source = try tempFile("in.txt", Data(vector.blob.plaintext.utf8))
    let sealed = source + ".enc"
    let opened = source + ".out"

    try BlobFrame.encryptFile(inputPath: source, outputPath: sealed, key: key(), blobPath: path)
    try BlobFrame.decryptFile(inputPath: sealed, outputPath: opened, key: key(), blobPath: path)

    XCTAssertEqual(try String(contentsOfFile: opened, encoding: .utf8), vector.blob.plaintext)
  }

  // A failed tag — tampered, or a blob fetched for another path — must leave
  // NOTHING at the output path: a consumer that found a partial plaintext there
  // would be reading unauthenticated bytes.
  func testWritesNothingWhenAuthenticationFails() throws {
    var tampered = try packed()
    tampered[tampered.index(before: tampered.endIndex)] ^= 0x01
    for (bytes, blobPath) in [(tampered, path), (try packed(), "files/other.enc")] {
      let source = try tempFile("bad.enc", bytes)
      let output = source + ".out"

      XCTAssertThrowsError(
        try BlobFrame.decryptFile(
          inputPath: source, outputPath: output, key: key(), blobPath: blobPath))

      XCTAssertFalse(FileManager.default.fileExists(atPath: output))
    }
  }

  // expo-file-system hands out file:// URIs, expo-crypto's own callers hand out
  // plain paths; both must reach the same file.
  func testResolvesFileURIsAndPlainPathsAlike() throws {
    let path = try tempFile("x.bin", Data([1, 2, 3]))

    XCTAssertEqual(BlobFrame.fileURL(path).path, path)
    XCTAssertEqual(BlobFrame.fileURL(URL(fileURLWithPath: path).absoluteString).path, path)
  }
}
